/* Regenerate src/lib/artifact/embed.css from the artifact generator's own shell.
 *
 *   node scripts/lift-artifact-css.mjs
 *
 * A direct port of sub_modules_examples/canvas/build.py:artifact_component_css(),
 * which worked out what has to be dropped and what has to be added back. Keeping
 * it as a script rather than a hand-copied blob means the sub-module stays the
 * source of truth for how its own artifacts look.
 *
 * What is dropped: the token blocks (:root and the two dark blocks) and the body
 * rules. Inside a shadow root the tokens already inherit from the notebook's
 * :root — which uses the same names by design — and `body` means nothing there.
 * What is left is exactly the component styling, which the shadow root
 * encapsulates so the two stylesheets cannot reach each other.
 */
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const HERE = dirname(fileURLToPath(import.meta.url));
const REPO = resolve(HERE, "..", "..");
const SHELL = resolve(REPO, "sub_modules_examples/artifact_generator/shell/template.html");
const OUT = resolve(HERE, "..", "src/lib/artifact/embed.css");

const html = readFileSync(SHELL, "utf8");
const match = /<style>([\s\S]*?)<\/style>/.exec(html);
if (!match) throw new Error(`no <style> block in ${SHELL}`);

let css = match[1];
const start = css.indexOf("*{box-sizing"); // component rules begin here
if (start < 0) throw new Error("could not find where the component rules start");
css = css.slice(start);
css = css.replace(/html,body\{[^}]*\}/g, "");
css = css.replace(/\bbody\{[^}]*\}/g, "");

/* Media queries inside a shadow root still measure the VIEWPORT, so the
   artifact's own responsive rules never fire when it is embedded in a notebook
   column narrower than the window. Restack it explicitly for this context.
   These are appended AFTER the lifted rules, not prepended: same specificity,
   so source order decides, and the canvas build.py only got away with putting
   them first because it prefixed every selector with .nty-artifact-host. */
const embed = [
  ":host{display:block;font:15px/1.55 var(--sans,-apple-system,BlinkMacSystemFont,'Segoe UI',Inter,Roboto,sans-serif);color:var(--ink);-webkit-font-smoothing:antialiased}",
  ".wrap{max-width:none;padding:14px 16px 20px}",
  ".grid{grid-template-columns:minmax(0,1fr)}",
  ".side{flex-direction:row;align-items:stretch;gap:12px}",
  ".side>.card{flex:1;min-width:0}",
  "canvas{height:280px}",
  ".lesson h1{font-size:21px}",
  "",
].join("\n");

const header =
  "/* GENERATED by scripts/lift-artifact-css.mjs — do not edit by hand.\n" +
  "   Source: sub_modules_examples/artifact_generator/shell/template.html\n" +
  "   Loaded with ?inline and injected into a shadow root by ArtifactBlock.tsx. */\n";

writeFileSync(OUT, header + css.trim() + "\n\n/* --- embedded-context overrides --- */\n" + embed);
console.log(`wrote ${OUT} — ${Math.round((embed.length + css.length) / 1024)} KB`);
